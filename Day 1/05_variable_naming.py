# Day 001 - Variable Naming Rules

# Good variable names
city = "Chennai"
pet_name = "Bruno"
favorite_language = "Python"

print("City:", city)
print("Pet Name:", pet_name)
print("Favorite Language:", favorite_language)

# Variable Naming Rules:
# 1. Use descriptive names.
# 2. Do not use spaces.
# 3. Do not start with numbers.
# 4. Avoid Python keywords like print, input, if, for, etc.
# 5. Use snake_case for multiple words.